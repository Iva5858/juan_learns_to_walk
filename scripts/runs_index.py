"""Write runs/INDEX.md: every trained run, by generation, with when it finished, its training steps (counting the runs before it),
the run it resumed from, whether it is exported for the robot, and its note (docs/runs.md).

    python scripts/runs_index.py                 # after training, or after moving runs around
    python scripts/runs_index.py --note v7/juan_v7_13_straight "safe on the robot: walks at ~25% of the command"
"""
import argparse
import json
import re
from datetime import datetime
from pathlib import Path

import numpy as np

from biped_rl.runs import RUNS

POLICIES = Path("robot/policies")


def runs():
    """Run folders (a final or best model inside), sorted by generation then name."""
    found = {p.parent for pattern in ("final_model.zip", "best_model.zip") for p in RUNS.rglob(pattern)}
    def key(d):  # archive last; numbers in order (v7_9 before v7_10, v9 before v10)
        rel = str(d.relative_to(RUNS))
        return rel.startswith("archive"), [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", rel)]
    return sorted(found, key=key)


def steps(run):
    record = run / "run.json"
    if record.exists() and json.loads(record.read_text()).get("total_steps"):
        return json.loads(record.read_text())["total_steps"]
    evals = run / "evaluations.npz"
    if evals.exists():
        t = np.load(evals)["timesteps"]
        return int(t[-1]) if len(t) else None
    return None


def row(run):
    model = run / "final_model.zip" if (run / "final_model.zip").exists() else run / "best_model.zip"
    record = json.loads((run / "run.json").read_text()) if (run / "run.json").exists() else {}
    note = (run / "note.txt").read_text().strip().splitlines()[0] if (run / "note.txt").exists() else ""
    n = steps(run)
    parent = record.get("parent") or ""
    return [f"`{run.name}`", datetime.fromtimestamp(model.stat().st_mtime).strftime("%Y-%m-%d %H:%M"),
            f"{n / 1e6:.0f}M" if n else "", f"`{parent}`" if parent else "",
            "yes" if (POLICIES / f"{run.name}.npz").exists() else "", note]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--note", nargs=2, metavar=("RUN", "TEXT"), help="set a run's note (runs/<RUN>/note.txt)")
    a = p.parse_args()
    if a.note:
        run = RUNS / a.note[0]
        if not run.is_dir():
            raise SystemExit(f"no run {run}")
        (run / "note.txt").write_text(a.note[1] + "\n")
    lines = ["# Runs", "",
             "Generated by `python scripts/runs_index.py`: don't edit (notes go in each run's note.txt, "
             "`--note`). Layout and naming: docs/runs.md.", ""]
    group = None
    for run in runs():
        g = str(run.parent.relative_to(RUNS))
        if g != group:
            group = g
            lines += ["", f"## {g}", "", "| run | finished | total steps | resumed from | on robot | note |",
                      "|---|---|---|---|---|---|"]
        lines.append("| " + " | ".join(row(run)) + " |")
    (RUNS / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {RUNS / 'INDEX.md'} ({len(runs())} runs)")


if __name__ == "__main__":
    main()
